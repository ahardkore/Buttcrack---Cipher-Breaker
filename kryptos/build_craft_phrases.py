import re

all_phrases = set()

# 1. From whitesmith_cribs.txt
try:
    with open("whitesmith_cribs.txt") as f:
        for line in f:
            clean = re.sub(r'[^A-Z]', '', line.strip().upper())
            if len(clean) >= 18:
                for i in range(len(clean) - 17):
                    all_phrases.add(clean[i : i + 18])
except Exception as e:
    print("Error reading whitesmith_cribs.txt:", e)

