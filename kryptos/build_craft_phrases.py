# 3. From Hendrie Book 3 excerpts
try:
    with open("theophilus_book3_english.txt") as f:
        txt = f.read()
    words = re.findall(r'[A-Z]+', txt.upper())
    clean_book3 = "".join(words)
    # Sample every 5th substring to keep size reasonable
    for i in range(0, len(clean_book3) - 17, 3):
        all_phrases.add(clean_book3[i : i + 18])
except Exception as e:
    print("Error reading theophilus_book3_english.txt:", e)

phrases_list = sorted(list(all_phrases))
print(f"Total compiled craft phrases: {len(phrases_list)}")

with open("craft_phrases_18.txt", "w") as f:
    for p in phrases_list:
        f.write(p + "\n")

print("Saved to craft_phrases_18.txt!")
